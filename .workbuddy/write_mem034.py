def app(path, text):
    raw = text.encode("utf-8")
    assert b"\r" not in raw, path
    with open(path, "ab") as f:
        f.write(raw)
    with open(path, "rb") as f:
        allb = f.read()
    assert allb.count(b"\r") == 0, "CRLF appeared in " + path
    print("appended %d bytes -> %s (lines %d)" % (len(raw), os.path.basename(path), allb.count(b"\n")))


