def rep(old, new, cnt=1, tag=""):
    global s, n
    got = s.count(old)
    assert got == cnt, "REP FAIL[%s] expect=%d got=%d :: %r" % (tag, cnt, got, old[:90])
    s = s.replace(old, new)
    n += 1
    print("  ok  %-42s x%d" % (tag, cnt))


def append_row(prefix, add, tag=""):
    """按行首前缀定位唯一一行，在「 | 状态 |」收尾前追加内容。"""
    global s, n
    lines = s.split("\n")
    idx = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    assert len(idx) == 1, "ROW FAIL[%s] matched %d :: %r" % (tag, len(idx), prefix)
    i = idx[0]
    assert lines[i].endswith(" | 演进中 |"), "ROW FAIL[%s] tail :: %r" % (tag, lines[i][-40:])
    lines[i] = lines[i][: -len(" | 演进中 |")] + add + " | 演进中 |"
    s = "\n".join(lines)
    n += 1
    print("  ok  %-42s x1 (row)" % tag)


