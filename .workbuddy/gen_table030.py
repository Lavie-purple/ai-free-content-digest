DATE_RE = re.compile(r"(\d{1,2})/(\d{1,2})")
out = [header, sep]
applied_rewrite = set()
for r in body:
    name = r.strip().strip("|").split("|")[0].strip()
    hit = None
    for k in REWRITE:
        if name.startswith(k):
            hit = k
            break
    if hit:
        out.append(REWRITE[hit])
        applied_rewrite.add(hit)
        continue
    cells = r.strip().strip("|").split("|")
    if len(cells) == 3 and "距今" in cells[2]:
        m = DATE_RE.search(cells[1])
        if m:
            mm, dd = int(m.group(1)), int(m.group(2))
            try:
                d = date(2026, mm, dd)
                delta = (d - date(2026, 10, 11)).days
                cells[2] = re.sub(r"距今\s*\d+\s*天", f"距今 {delta} 天", cells[2])
                r = "|" + "|".join(cells) + "|"
            except ValueError:
                pass
    # 继承行归属化：未被本期改写的行里的「本期」指写入该行的那一期（多为 029 期），不要被读成当期
    r = r.replace("（本期登记）", "（029 期登记）").replace("本期", "（029 期）")
    out.append(r)

missing = set(REWRITE) - applied_rewrite
assert not missing, missing
