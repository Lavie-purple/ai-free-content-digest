def rep(old, new, cnt=1, tag=""):
    global s, n
    got = s.count(old)
    assert got == cnt, "REP FAIL[%s] expect=%d got=%d :: %r" % (tag, cnt, got, old[:90])
    s = s.replace(old, new)
    n += 1
    print("  ok  %-44s x%d" % (tag, cnt))


def append_row(prefix, add, tag="", tail=" | 演进中 |"):
    """按行首前缀定位唯一一行，在收尾状态列前追加内容。"""
    global s, n
    lines = s.split("\n")
    idx = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    assert len(idx) == 1, "ROW FAIL[%s] matched %d :: %r" % (tag, len(idx), prefix)
    i = idx[0]
    assert lines[i].endswith(tail), "ROW FAIL[%s] tail :: %r" % (tag, lines[i][-40:])
    lines[i] = lines[i][: -len(tail)] + add + tail
    s = "\n".join(lines)
    n += 1
    print("  ok  %-44s x1 (row)" % tag)


