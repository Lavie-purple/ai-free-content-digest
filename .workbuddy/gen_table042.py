# ⚠️ **042 期修掉一个继承下来的诊断失效缺陷（041 期脚本原样照抄了040 期的写法）**：
#    原写法是 `out = [recompute(l) ...]` **就地覆盖 out**，然后再遍历 out 打印 before->after diff。
#    但那时 out 里已经全是重算后的新值了，**拿新值去和真值比，永远相等 -> diff 恒为空**。
#    即：041 期（含 040 期）脚注里那句「before -> after diff」**从来没有真正输出过任何一行**，
