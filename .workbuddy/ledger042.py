# ---- 先算小节区间，再把行插到「所属小节的末尾」 ----
HDR = re.compile(r"^(#{2,4}) (.*?)（(\d+)）\s*$")


def section_ranges(ls):
    """返回 [(标题, 起始idx, 结束idx)]，结束idx 为该节最后一行（含空行）的下一位。"""
    heads = []
    for i, l in enumerate(ls):
        m = HDR.match(l)
        if m:
            heads.append((i, len(m.group(1)), m.group(2).strip()))
    out = []
    for k, (i, lvl, name) in enumerate(heads):
        nxt = len(ls)
        for j, l2, name2 in heads[k + 1:]:
            if l2 <= lvl:
                nxt = j
                break
        out.append((name, i, nxt))
    return out


