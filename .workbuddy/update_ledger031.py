chk = io.open(LEDGER, encoding="utf-8").read().split("\n")
def cnt(a, b):
    n = 0
    for l in chk[a:b]:
        if l.startswith("|") and not l.startswith("| ---") and not l.startswith("| 信源"):
            n += 1
    return n

def idx(prefix):
    for i, l in enumerate(chk):
        if l.startswith(prefix):
            return i
    raise AssertionError(prefix)

top = idx("## T0 · 根节点")
t1 = idx("## T1 · 社区与社交")
